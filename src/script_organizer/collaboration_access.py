from __future__ import annotations

import json
import os
import re
import secrets
import tempfile
from datetime import datetime, timezone
from pathlib import Path
from threading import RLock
from typing import Any

from .workspace_db import workspace_database_path


ROLES = ("viewer", "reviewer", "manager")
STATUSES = ("active", "disabled")
_ROLE_ORDER = {role: index for index, role in enumerate(ROLES)}
_DEVICE_ID = re.compile(r"^[A-Za-z0-9._-]{12,120}$")
_MAX_AUDIT_ROWS = 500
_TOUCH_INTERVAL_SECONDS = 60


def _now() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


def _parse_time(value: object) -> datetime | None:
    try:
        return datetime.fromisoformat(str(value).replace("Z", "+00:00"))
    except (TypeError, ValueError):
        return None


def _clean_nickname(value: object, *, required: bool = False) -> str:
    nickname = " ".join(str(value or "").split())[:40]
    if required and not nickname:
        raise ValueError("请填写审核昵称")
    return nickname


class CollaborationAccessStore:
    """Host-local browser identities, roles, and access evidence.

    Browser device identifiers are intentionally pseudonymous and generated by
    the browser. IP addresses are audit metadata only. This store never joins
    shared review/project artifacts and is not a cross-device login system.
    """

    _locks: dict[Path, RLock] = {}
    _locks_guard = RLock()

    def __init__(self, workspace_id: str, path: Path | None = None):
        self.workspace_id = str(workspace_id or "").strip()
        if not self.workspace_id:
            raise ValueError("workspace_id 不能为空")
        self.path = path or workspace_database_path(self.workspace_id).parent / "collaborators.json"
        self.path.parent.mkdir(parents=True, exist_ok=True)
        with self._locks_guard:
            self._lock = self._locks.setdefault(self.path.resolve(), RLock())

    @staticmethod
    def valid_device_id(value: object) -> bool:
        return bool(_DEVICE_ID.fullmatch(str(value or "")))

    def _load(self) -> dict[str, Any]:
        try:
            with self.path.open(encoding="utf-8") as handle:
                payload = json.load(handle)
        except (OSError, ValueError):
            payload = {}
        if not isinstance(payload, dict):
            payload = {}
        users = payload.get("users")
        devices = payload.get("devices")
        audit = payload.get("audit")
        return {
            "version": 1,
            "users": users if isinstance(users, dict) else {},
            "devices": devices if isinstance(devices, dict) else {},
            "audit": audit if isinstance(audit, list) else [],
        }

    def _save(self, payload: dict[str, Any]) -> None:
        fd, temporary = tempfile.mkstemp(prefix=self.path.name + ".", suffix=".tmp", dir=self.path.parent)
        try:
            with os.fdopen(fd, "w", encoding="utf-8") as handle:
                json.dump(payload, handle, ensure_ascii=False, indent=2)
                handle.flush()
                os.fsync(handle.fileno())
            os.replace(temporary, self.path)
        finally:
            if os.path.exists(temporary):
                os.unlink(temporary)
        try:
            os.chmod(self.path, 0o600)
        except OSError:
            pass

    @staticmethod
    def _audit(payload: dict[str, Any], event: str, user: dict[str, Any], device: dict[str, Any] | None = None) -> None:
        row = {
            "at": _now(),
            "event": event,
            "user_id": str(user.get("user_id", "") or ""),
            "nickname": str(user.get("nickname", "") or ""),
            "role": str(user.get("role", "") or ""),
            "ip": str((device or {}).get("last_ip", "") or ""),
            "device_id": str((device or {}).get("device_id", "") or "")[-12:],
        }
        payload["audit"] = ([row] + list(payload.get("audit", [])))[:_MAX_AUDIT_ROWS]

    @staticmethod
    def _public_user(payload: dict[str, Any], user: dict[str, Any]) -> dict[str, Any]:
        user_id = str(user.get("user_id", "") or "")
        devices = [
            device for device in payload.get("devices", {}).values()
            if isinstance(device, dict) and str(device.get("user_id", "") or "") == user_id
        ]
        return {
            "user_id": user_id,
            "nickname": str(user.get("nickname", "") or ""),
            "role": str(user.get("role", "viewer") or "viewer"),
            "status": str(user.get("status", "active") or "active"),
            "created_at": str(user.get("created_at", "") or ""),
            "updated_at": str(user.get("updated_at", "") or ""),
            "last_seen_at": str(user.get("last_seen_at", "") or ""),
            "last_ip": str(user.get("last_ip", "") or ""),
            "device_count": len(devices),
        }

    def observe(
        self,
        device_id: str,
        *,
        ip: str,
        user_agent: str = "",
        local: bool = False,
        paired: bool = True,
    ) -> dict[str, Any]:
        if not self.valid_device_id(device_id):
            raise ValueError("浏览器设备标识无效，请刷新页面后重试")
        with self._lock:
            payload = self._load()
            devices = payload["devices"]
            users = payload["users"]
            device = devices.get(device_id)
            changed = False
            if not isinstance(device, dict) or not isinstance(users.get(str(device.get("user_id", "") or "")), dict):
                now = _now()
                user_id = "usr_" + secrets.token_urlsafe(12)
                # Preserve the existing team-review workflow: a browser that
                # reached the Host can review immediately. Managers can later
                # downgrade individual browser identities to viewer.
                role = "manager" if local else "reviewer"
                user = {
                    "user_id": user_id,
                    "nickname": "",
                    "role": role,
                    "status": "active",
                    "created_at": now,
                    "updated_at": now,
                    "last_seen_at": now,
                    "last_ip": str(ip or "")[:80],
                }
                device = {
                    "device_id": device_id,
                    "user_id": user_id,
                    "created_at": now,
                    "last_seen_at": now,
                    "last_ip": str(ip or "")[:80],
                    "user_agent": str(user_agent or "")[:300],
                }
                users[user_id] = user
                devices[device_id] = device
                self._audit(payload, "browser_connected", user, device)
                changed = True
            else:
                user = users[str(device["user_id"])]
                last_seen = _parse_time(device.get("last_seen_at"))
                now = datetime.now(timezone.utc)
                stale = last_seen is None or (now - last_seen).total_seconds() >= _TOUCH_INTERVAL_SECONDS
                if stale:
                    timestamp = _now()
                    device["last_seen_at"] = timestamp
                    device["last_ip"] = str(ip or "")[:80]
                    device["user_agent"] = str(user_agent or "")[:300]
                    user["last_seen_at"] = timestamp
                    user["last_ip"] = str(ip or "")[:80]
                    user["updated_at"] = timestamp
                    self._audit(payload, "browser_seen", user, device)
                    changed = True
            if changed:
                self._save(payload)
            return self._public_user(payload, user)

    def rename(self, device_id: str, nickname: object, **context: Any) -> dict[str, Any]:
        nickname = _clean_nickname(nickname, required=True)
        with self._lock:
            payload = self._load()
            user = self._user_for_device(payload, device_id)
            if str(user.get("status", "")) == "disabled":
                raise PermissionError("当前用户已被停用")
            if user.get("nickname") != nickname:
                user["nickname"] = nickname
                user["updated_at"] = _now()
                self._audit(payload, "nickname_changed", user, payload["devices"].get(device_id))
                self._save(payload)
            return self._public_user(payload, user)

    def _user_for_device(self, payload: dict[str, Any], device_id: str) -> dict[str, Any]:
        device = payload.get("devices", {}).get(device_id)
        if not isinstance(device, dict):
            raise PermissionError("浏览器身份尚未登记")
        user = payload.get("users", {}).get(str(device.get("user_id", "") or ""))
        if not isinstance(user, dict):
            raise PermissionError("浏览器身份无效")
        return user

    def current_user(self, device_id: str) -> dict[str, Any]:
        with self._lock:
            payload = self._load()
            return self._public_user(payload, self._user_for_device(payload, device_id))

    @staticmethod
    def require_role(user: dict[str, Any], role: str) -> None:
        if str(user.get("status", "active") or "active") != "active":
            raise PermissionError("当前用户已被停用")
        if _ROLE_ORDER.get(str(user.get("role", "viewer") or "viewer"), -1) < _ROLE_ORDER[role]:
            raise PermissionError("当前权限不足")

    def list_users(self) -> list[dict[str, Any]]:
        with self._lock:
            payload = self._load()
            users = [
                self._public_user(payload, user)
                for user in payload["users"].values()
                if isinstance(user, dict)
            ]
        return sorted(users, key=lambda user: (user["status"] != "active", user["nickname"] or "~", user["user_id"]))

    def update_user(self, user_id: str, values: object) -> dict[str, Any]:
        if not isinstance(values, dict):
            raise ValueError("用户设置必须是对象")
        with self._lock:
            payload = self._load()
            user = payload["users"].get(str(user_id or ""))
            if not isinstance(user, dict):
                raise ValueError("用户不存在")
            if "role" in values:
                role = str(values.get("role", "") or "")
                if role not in ROLES:
                    raise ValueError("角色无效")
                user["role"] = role
            if "status" in values:
                status = str(values.get("status", "") or "")
                if status not in STATUSES:
                    raise ValueError("状态无效")
                user["status"] = status
            if "nickname" in values:
                user["nickname"] = _clean_nickname(values.get("nickname"), required=False)
            user["updated_at"] = _now()
            self._audit(payload, "user_updated", user)
            self._save(payload)
            return self._public_user(payload, user)

    def audit(self, limit: int = 80) -> list[dict[str, Any]]:
        with self._lock:
            payload = self._load()
            return [dict(item) for item in payload["audit"][:max(1, min(int(limit), _MAX_AUDIT_ROWS))] if isinstance(item, dict)]
